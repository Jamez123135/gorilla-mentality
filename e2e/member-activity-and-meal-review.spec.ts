import { test, expect } from "@playwright/test";
import { clerk } from "@clerk/testing/playwright";
import { createClerkClient } from "@clerk/backend";
import { PrismaClient } from "@prisma/client";

test.describe("extra activities and explicit meal review", () => {
  test.skip(!process.env.DATABASE_URL?.includes("127.0.0.1:54329") || !process.env.NEXT_PUBLIC_CLERK_PUBLISHABLE_KEY?.startsWith("pk_test_"), "Local development services only");
  const backend = createClerkClient({ secretKey: process.env.CLERK_SECRET_KEY });
  const database = new PrismaClient();
  let userId: string;
  let email: string;
  test.beforeAll(async ({}, info) => {
    email = `activities-${info.project.name}-${Date.now()}+clerk_test@example.com`;
    userId = (await backend.users.createUser({ emailAddress: [email], firstName: "ActivityMember", skipPasswordRequirement: true })).id;
    await database.profile.create({ data: { id: userId, targetCalories: 2100, targetProtein: 150 } });
  });
  test.afterAll(async () => {
    if (userId) { await database.profile.deleteMany({ where: { id: userId } }); await backend.users.deleteUser(userId); }
    await database.$disconnect();
  });
  test("logs exercises without a plan, records cardio, and keeps them through reload and history", async ({ page }, info) => {
    await page.goto("/login"); await clerk.signIn({ page, emailAddress: email });
    await page.goto("/dashboard/workouts");
    await page.getByRole("button", { name: "Log another exercise", exact: true }).click();
    await page.getByLabel("Exercise name", { exact: true }).fill("My extra dumbbell curl");
    await page.getByLabel("Activity weight unit").selectOption("kg");
    await page.getByLabel("Activity set 1 weight").fill("10");
    await page.getByLabel("Activity set 1 reps").fill("12");
    await page.getByRole("button", { name: "Add performed set", exact: true }).click();
    await page.getByLabel("Activity set 2 reps").fill("10");
    await page.getByRole("button", { name: "Save exercise", exact: true }).click();
    await expect(page.getByText("Exercise saved.", { exact: true })).toBeVisible();
    await page.getByRole("button", { name: "Log cardio", exact: true }).click();
    await page.getByLabel("Cardio activity", { exact: true }).fill("Running");
    await page.getByLabel("Cardio duration (minutes)").fill("30");
    await page.getByLabel("Cardio distance", { exact: true }).fill("5");
    await page.getByRole("button", { name: "Save cardio", exact: true }).click();
    await expect(page.getByText("Cardio saved.", { exact: true })).toBeVisible();
    expect(await database.workoutSession.count({ where: { userId } })).toBe(0);
    expect(await database.workoutActivity.count({ where: { userId } })).toBe(2);
    await page.reload();
    await page.getByText("Your additional activities (2)", { exact: true }).click();
    await expect(page.getByRole("heading", { name: "Running", exact: true })).toBeVisible();
    await page.goto("/dashboard/workouts/history");
    await expect(page.getByRole("heading", { name: "My extra dumbbell curl", exact: true })).toBeVisible();
    await expect(page.getByText("30 min / 5 km", { exact: true })).toBeVisible();
    await page.goto("/dashboard");
    await expect(page.getByText("Additional activities this week: 2 / Cardio: 30 min", { exact: true })).toBeVisible();
    await database.profile.update({ where: { id: userId }, data: { sex: "male", trainingDays: 3 } });
    await page.goto("/dashboard/workouts");
    const reference = page.getByRole("img", { name: /movement reference/ }).first();
    await expect(reference).toBeVisible();
    await expect.poll(() => reference.evaluate((img: HTMLImageElement) => img.naturalWidth)).toBeGreaterThan(0);
    await page.getByText("See movement photos", { exact: true }).first().click();
    await expect(page.getByRole("img", { name: /position 2/ }).first()).toBeVisible();
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
    await page.screenshot({ path: info.outputPath("workout-photos.png"), fullPage: true });
  });
  test("calculator and pantry fill Add meal but only the final button writes to the diary", async ({ page }, info) => {
    await page.goto("/login"); await clerk.signIn({ page, emailAddress: email });
    await page.goto("/dashboard/nutrition");
    const day = await page.getByLabel("Food diary date").inputValue();
    const logDate = new Date(`${day}T00:00:00.000Z`);
    await database.nutritionLog.upsert({ where: { userId_logDate: { userId, logDate } }, create: { userId, logDate, calories: 50, protein: 5 }, update: { calories: 50, protein: 5 } });
    await page.reload();
    await page.getByRole("tab", { name: "Meal calculator", exact: true }).click();
    await page.getByTestId("pick-meal-chicken").click();
    await page.getByLabel("Ingredient 1 grams").fill("200");
    await page.getByLabel("Calculated meal name").fill("Reviewed chicken");
    await page.getByRole("button", { name: "Save to Add meal", exact: true }).click();
    await expect(page.getByRole("tab", { name: "Add meal", exact: true })).toHaveAttribute("aria-selected", "true");
    await expect(page.getByLabel("Calories", { exact: true })).toHaveValue("330");
    page.once("dialog", (dialog) => dialog.accept());
    await page.getByRole("button", { name: "Delete previous daily total", exact: true }).click();
    await expect(page.getByText("Entry deleted.", { exact: true })).toBeVisible();
    await expect(page.getByLabel("Food or meal")).toHaveValue("Reviewed chicken");
    await expect(page.getByLabel("Calories", { exact: true })).toHaveValue("330");
    expect(await database.mealEntry.count({ where: { userId } })).toBe(0);
    await page.getByLabel("Food or meal").fill("My reviewed chicken");
    await page.getByRole("button", { name: "Add meal", exact: true }).click();
    await expect(page.getByText("Meal saved.", { exact: true })).toBeVisible();
    const saved = await database.mealEntry.findFirstOrThrow({ where: { userId, name: "My reviewed chicken" } });
    expect(saved.calories).toBe(330);
    expect(JSON.stringify(saved.ingredients)).toContain("chicken");
    await page.getByRole("tab", { name: "Pantry ideas", exact: true }).click();
    await page.getByLabel("Available ingredients", { exact: true }).fill("chicken, rice, broccoli");
    await page.getByRole("button", { name: "Use meal idea", exact: true }).first().click();
    await expect(page.getByRole("tab", { name: "Add meal", exact: true })).toHaveAttribute("aria-selected", "true");
    await expect(page.getByLabel("Food or meal")).not.toHaveValue("");
    expect(await database.mealEntry.count({ where: { userId } })).toBe(1);
    await page.screenshot({ path: info.outputPath("meal-review.png"), fullPage: true });
    await page.getByRole("button", { name: "Add meal", exact: true }).click();
    await expect(page.getByText("Meal saved.", { exact: true })).toBeVisible();
    expect(await database.mealEntry.count({ where: { userId } })).toBe(2);
    await page.reload();
    await expect(page.getByText("My reviewed chicken", { exact: true })).toBeVisible();
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  });
});
